-- GEOSTORE: persistent support ticket threads with secure guest access.
-- This migration preserves support_tickets and its legacy message/reply fields.
ALTER TABLE public.support_tickets
  ADD COLUMN IF NOT EXISTS customer_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS access_token_hash text;
ALTER TABLE public.support_tickets DROP CONSTRAINT IF EXISTS support_tickets_access_token_hash_check;
ALTER TABLE public.support_tickets ADD CONSTRAINT support_tickets_access_token_hash_check
  CHECK (access_token_hash IS NULL OR access_token_hash ~ '^[a-f0-9]{64}$');
CREATE INDEX IF NOT EXISTS support_tickets_customer_user_id_idx
  ON public.support_tickets(customer_user_id) WHERE customer_user_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.support_ticket_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id text REFERENCES public.support_tickets(id) ON DELETE SET NULL,
  ticket_ref text NOT NULL CHECK (char_length(btrim(ticket_ref)) BETWEEN 1 AND 64),
  sender_role text NOT NULL CHECK (sender_role IN ('customer','admin')),
  sender_name text NOT NULL CHECK (char_length(btrim(sender_name)) BETWEEN 1 AND 100),
  message text NOT NULL CHECK (char_length(btrim(message)) BETWEEN 1 AND 4000),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS support_ticket_messages_ticket_ref_created_idx
  ON public.support_ticket_messages(ticket_ref,created_at,id);
CREATE INDEX IF NOT EXISTS support_ticket_messages_ticket_id_idx
  ON public.support_ticket_messages(ticket_id);
ALTER TABLE public.support_ticket_messages ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Admins can read support ticket messages" ON public.support_ticket_messages;
CREATE POLICY "Admins can read support ticket messages" ON public.support_ticket_messages
  FOR SELECT TO authenticated USING (
    coalesce((select auth.jwt())->'app_metadata'->>'role','')='admin'
    AND (select auth.uid())='1060de3d-d28a-45f8-9a64-5e0368cffc4b'::uuid
  );
REVOKE ALL ON public.support_ticket_messages FROM anon,authenticated;
GRANT SELECT ON public.support_ticket_messages TO authenticated;
GRANT ALL ON public.support_ticket_messages TO service_role;
GRANT USAGE,SELECT ON SEQUENCE public.support_ticket_messages_id_seq TO service_role;

DROP POLICY IF EXISTS "Visitors can submit validated support tickets" ON public.support_tickets;
CREATE POLICY "Visitors can submit validated support tickets" ON public.support_tickets
  FOR INSERT TO anon,authenticated WITH CHECK (
    char_length(btrim(id)) BETWEEN 1 AND 64
    AND char_length(btrim(customer_name)) BETWEEN 1 AND 100
    AND char_length(btrim(message)) BETWEEN 1 AND 4000
    AND (email IS NULL OR char_length(email)<=254)
    AND (subject IS NULL OR char_length(subject)<=150)
    AND status='ღია' AND reply IS NULL
    AND customer_user_id IS NULL AND access_token_hash IS NULL
  );

-- Backfill existing ticket messages and saved admin replies without deleting old data.
INSERT INTO public.support_ticket_messages(ticket_id,ticket_ref,sender_role,sender_name,message,created_at)
SELECT t.id,t.id,'customer',t.customer_name,t.message,t.created_at
FROM public.support_tickets t
WHERE NOT EXISTS (SELECT 1 FROM public.support_ticket_messages m WHERE m.ticket_ref=t.id AND m.sender_role='customer');
INSERT INTO public.support_ticket_messages(ticket_id,ticket_ref,sender_role,sender_name,message,created_at)
SELECT t.id,t.id,'admin','GEOSTORE',t.reply,t.created_at
FROM public.support_tickets t
WHERE nullif(btrim(t.reply),'') IS NOT NULL
AND NOT EXISTS (SELECT 1 FROM public.support_ticket_messages m WHERE m.ticket_ref=t.id AND m.sender_role='admin');

CREATE OR REPLACE FUNCTION private.create_support_ticket(
 p_id text,p_customer_name text,p_email text,p_subject text,p_message text,p_access_token text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $$
DECLARE
 v_created_at timestamptz;
 v_name text:=btrim(coalesce(p_customer_name,''));
 v_message text:=btrim(coalesce(p_message,''));
 v_email text:=nullif(lower(btrim(coalesce(p_email,''))),'');
 v_subject text:=nullif(btrim(coalesce(p_subject,'')),'');
BEGIN
 IF coalesce(length(btrim(p_id)),0) NOT BETWEEN 6 AND 64 OR p_id !~ '^[A-Za-z0-9_-]{6,64}$'
 OR coalesce(length(v_name),0) NOT BETWEEN 2 AND 100
 OR coalesce(length(v_message),0) NOT BETWEEN 1 AND 4000
 OR coalesce(length(v_email),0)>254 OR coalesce(length(v_subject),0)>150
 OR coalesce(p_access_token,'') !~ '^[A-Fa-f0-9]{64}$'
 THEN RAISE EXCEPTION 'მხარდაჭერის მოთხოვნის მონაცემები არასწორია.'; END IF;
 INSERT INTO public.support_tickets(id,customer_name,email,subject,message,status,reply,created_at,customer_user_id,access_token_hash)
 VALUES(p_id,v_name,v_email,v_subject,v_message,'ღია',NULL,now(),auth.uid(),
 encode(extensions.digest(lower(p_access_token),'sha256'),'hex'))
 RETURNING created_at INTO v_created_at;
 INSERT INTO public.support_ticket_messages(ticket_id,ticket_ref,sender_role,sender_name,message,created_at)
 VALUES(p_id,p_id,'customer',v_name,v_message,v_created_at);
 RETURN jsonb_build_object('ticket_id',p_id,'status','ღია','created_at',v_created_at);
END; $$;

CREATE OR REPLACE FUNCTION private.get_support_ticket_messages(p_ticket_id text,p_access_token text DEFAULT NULL)
RETURNS TABLE(id bigint,sender_role text,sender_name text,message text,created_at timestamptz)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $$
DECLARE v_ticket public.support_tickets%rowtype; v_is_admin boolean; v_is_customer boolean;
BEGIN
 SELECT t.* INTO v_ticket FROM public.support_tickets t WHERE t.id=p_ticket_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'მხარდაჭერის მოთხოვნა ვერ მოიძებნა.'; END IF;
 v_is_admin:=coalesce(auth.jwt()->'app_metadata'->>'role','')='admin'
 AND auth.uid()='1060de3d-d28a-45f8-9a64-5e0368cffc4b'::uuid;
 v_is_customer:=(v_ticket.customer_user_id IS NOT NULL AND auth.uid()=v_ticket.customer_user_id)
 OR (auth.uid() IS NOT NULL AND v_ticket.email IS NOT NULL
 AND lower(v_ticket.email)=lower(coalesce(auth.jwt()->>'email','')))
 OR (coalesce(p_access_token,'') ~ '^[A-Fa-f0-9]{64}$' AND v_ticket.access_token_hash IS NOT NULL
 AND v_ticket.access_token_hash=encode(extensions.digest(lower(p_access_token),'sha256'),'hex'));
 IF NOT(v_is_admin OR v_is_customer) THEN
 RAISE EXCEPTION 'მიმოწერის ნახვის უფლება არ გაქვთ.' USING ERRCODE='42501'; END IF;
 RETURN QUERY SELECT m.id,m.sender_role,m.sender_name,m.message,m.created_at
 FROM public.support_ticket_messages m WHERE m.ticket_ref=p_ticket_id ORDER BY m.created_at,m.id;
END; $$;

CREATE OR REPLACE FUNCTION private.add_support_ticket_message(p_ticket_id text,p_message text,p_access_token text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $$
DECLARE
 v_ticket public.support_tickets%rowtype; v_is_admin boolean; v_is_customer boolean;
 v_message text:=btrim(coalesce(p_message,'')); v_sender_role text; v_sender_name text;
 v_message_id bigint; v_created_at timestamptz;
BEGIN
 IF coalesce(length(v_message),0) NOT BETWEEN 1 AND 4000 THEN
 RAISE EXCEPTION 'შეტყობინება უნდა შეიცავდეს 1-4000 სიმბოლოს.'; END IF;
 SELECT t.* INTO v_ticket FROM public.support_tickets t WHERE t.id=p_ticket_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'მხარდაჭერის მოთხოვნა ვერ მოიძებნა.'; END IF;
 v_is_admin:=coalesce(auth.jwt()->'app_metadata'->>'role','')='admin'
 AND auth.uid()='1060de3d-d28a-45f8-9a64-5e0368cffc4b'::uuid;
 v_is_customer:=(v_ticket.customer_user_id IS NOT NULL AND auth.uid()=v_ticket.customer_user_id)
 OR (auth.uid() IS NOT NULL AND v_ticket.email IS NOT NULL
 AND lower(v_ticket.email)=lower(coalesce(auth.jwt()->>'email','')))
 OR (coalesce(p_access_token,'') ~ '^[A-Fa-f0-9]{64}$' AND v_ticket.access_token_hash IS NOT NULL
 AND v_ticket.access_token_hash=encode(extensions.digest(lower(p_access_token),'sha256'),'hex'));
 IF NOT(v_is_admin OR v_is_customer) THEN
 RAISE EXCEPTION 'მიმოწერაში პასუხის დამატების უფლება არ გაქვთ.' USING ERRCODE='42501'; END IF;
 v_sender_role:=CASE WHEN v_is_admin THEN 'admin' ELSE 'customer' END;
 v_sender_name:=CASE WHEN v_is_admin THEN 'GEOSTORE' ELSE v_ticket.customer_name END;
 INSERT INTO public.support_ticket_messages(ticket_id,ticket_ref,sender_role,sender_name,message)
 VALUES(p_ticket_id,p_ticket_id,v_sender_role,v_sender_name,v_message)
 RETURNING id,created_at INTO v_message_id,v_created_at;
 IF v_is_admin THEN
 UPDATE public.support_tickets SET reply=v_message,status='მოგვარებული' WHERE id=p_ticket_id;
 ELSE UPDATE public.support_tickets SET status='ღია' WHERE id=p_ticket_id; END IF;
 RETURN jsonb_build_object('message_id',v_message_id,'ticket_id',p_ticket_id,
 'sender_role',v_sender_role,'created_at',v_created_at);
END; $$;

